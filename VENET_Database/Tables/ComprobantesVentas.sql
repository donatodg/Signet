CREATE TABLE [dbo].[ComprobantesVentas] (
    [Id]                            INT             IDENTITY (1, 1) NOT NULL,
    [Id_Sucursal]                   INT             NOT NULL,
    [Id_CentroCosto]                INT             NOT NULL,
    [Id_TipoComprobante]            INT             NOT NULL,
    [Id_TalonariosComprobantes]     INT             NOT NULL,
    [Letra]                         VARCHAR (2)     NOT NULL,
    [PuntoVenta]                    VARCHAR (4)     NOT NULL,
    [NroComprobante]                VARCHAR (8)     NOT NULL,
    [Id_TipoEntidad]                INT             NOT NULL,
    [Id_Entidad]                    INT             NOT NULL,
    [Id_Vendedor]                   INT             NOT NULL,
    [Id_FormaPago]                  INT             NOT NULL,
    [Id_EntidadDomicilioEntrega]    INT             NULL,
    [Fecha]                         DATE            NOT NULL,
    [FechaEntrega]                  DATE            NOT NULL,
    [FechaEntregado]                DATE            NULL,
