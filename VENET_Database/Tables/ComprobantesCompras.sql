CREATE TABLE [dbo].[ComprobantesCompras] (
    [Id]                  INT             IDENTITY (1, 1) NOT NULL,
    [Id_Sucursal]         INT             NOT NULL,
    [Id_CentroCosto]      INT             NOT NULL,
    [Id_TipoComprobante]  INT             NOT NULL,
    [Letra]               VARCHAR (2)     NOT NULL,
    [PuntoVenta]          VARCHAR (4)     NOT NULL,
    [NroComprobante]      VARCHAR (8)     NOT NULL,
    [Id_TipoEntidad]      INT             NOT NULL,
    [Id_Entidad]          INT             NOT NULL,
    [Id_FormaPago]        INT             NOT NULL,
    [Fecha]               DATE            NOT NULL,
    [FechaRecepcion]      DATE            NOT NULL,
    [FechaVto]            DATE            NOT NULL,
    [Observaciones]       VARCHAR (1000)  NOT NULL,
    [PercepcionIva]       DECIMAL (19, 2) NOT NULL,
    [OtrosImpuestos]      DECIMAL (19, 2) NOT NULL,
    [PercepcionGanancias] DECIMAL (19, 2) NOT NULL,
    [PercepcionIIBB]      DECIMAL (19, 2) NOT NULL,
    [Descuento]           DECIMAL (19, 2) NOT NULL,
    [FechaLiquidacion]    DATETIME        NULL,
    [FechaAnulacion]      DATETIME        NULL,
    [MotivoAnulacion]     VARCHAR (300)   NULL,
    [FechaAdd]            DATETIME        NOT NULL,
    [FechaMod]            DATETIME        NULL,
    [FechaDel]            DATETIME        NULL,
    [UserAdd]             INT             NOT NULL,
    [UserMod]             INT             NULL,
    [UserDel]             INT             NULL,
    CONSTRAINT [PK_ComprobantesCompras] PRIMARY KEY CLUSTERED ([Id] ASC),
    CONSTRAINT [FK_ComprobantesCompras_CentrosCostos] FOREIGN KEY ([Id_CentroCosto]) REFERENCES [dbo].[CentrosCostos] ([Id]),
    CONSTRAINT [FK_ComprobantesCompras_FormasPagos] FOREIGN KEY ([Id_FormaPago]) REFERENCES [dbo].[FormasPagos] ([Id]),
    CONSTRAINT [FK_ComprobantesCompras_Sucursales] FOREIGN KEY ([Id_Sucursal]) REFERENCES [dbo].[Sucursales] ([Id]),
    CONSTRAINT [FK_ComprobantesCompras_TipoComprobante] FOREIGN KEY ([Id_TipoComprobante]) REFERENCES [dbo].[TipoComprobante] ([Id])
);

