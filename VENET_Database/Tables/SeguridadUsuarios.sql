CREATE TABLE [dbo].[SeguridadUsuarios] (
    [Id]               INT              IDENTITY (1, 1) NOT NULL,
    [Id_Grupo]         INT              NOT NULL,
    [Username]         VARCHAR (50)     NOT NULL,
    [Apellido]         VARCHAR (50)     NOT NULL,
    [Nombre]           VARCHAR (50)     NOT NULL,
    [Clave]            VARCHAR (50)     NOT NULL,
    [Activo]           BIT              NOT NULL,
    [Email]            VARCHAR (50)     NULL,
    [Foto]             VARBINARY (8000) NULL,
    [Tema]             VARCHAR (100)    NULL,
    [BackColor]        VARCHAR (50)     NULL,
    [BackImage]        VARBINARY (8000) NULL,
    [RibbonMinimizado] BIT              CONSTRAINT [DF_SeguridadUsuarios_RibbonMinimizado] DEFAULT ((0)) NOT NULL,
    [TituloTile]       BIT              CONSTRAINT [DF_SeguridadUsuarios_TituloTile] DEFAULT ((0)) NOT NULL,
    [TileConfig]       XML              NULL,
    [FechaAdd]         DATETIME         NOT NULL,
    [FechaMod]         DATETIME         NULL,
    [FechaDel]         DATETIME         NULL,
    [UserAdd]          INT              NOT NULL,
    [UserMod]          INT              NULL,
    [UserDel]          INT              NULL,
    CONSTRAINT [PK_Usuarios] PRIMARY KEY CLUSTERED ([Id] ASC),
    CONSTRAINT [FK_Seguridad_Usuarios_Seguridad_Grupos] FOREIGN KEY ([Id_Grupo]) REFERENCES [dbo].[SeguridadGrupos] ([Id])
);

