CREATE TABLE [dbo].[Recibos] (
    [Id]                        INT            IDENTITY (1, 1) NOT NULL,
    [Id_Sucursal]               INT            NOT NULL,
    [Id_TalonariosComprobantes] INT            NOT NULL,
    [Id_CentroCosto]            INT            NOT NULL,
    [TipoEntidad]               INT            NOT NULL,
    [Id_Entidad]                INT            NOT NULL,
    [Fecha]                     DATE           NOT NULL,
    [Concepto]                  VARCHAR (100)  NOT NULL,
    [Letra]                     VARCHAR (1)    NOT NULL,
    [PuntoVenta]                VARCHAR (4)    NOT NULL,
    [NroComprobante]            VARCHAR (8)    NOT NULL,
    [Fecha_Liquidacion]         DATETIME       NULL,
    [Fecha_Anulacion]           DATETIME       NULL,
    [MotivoAnulacion]           VARCHAR (300)  NULL,
    [Id_Entidad_Mov]            INT            NULL,
    [Observaciones]             VARCHAR (3000) NULL,
    [FechaAdd]                  DATETIME       NOT NULL,
    [FechaMod]                  DATETIME       NULL,
    [FechaDel]                  DATETIME       NULL,
    [UserAdd]                   INT            NOT NULL,
    [UserMod]                   INT            NULL,
    [UserDel]                   INT            NULL,
    CONSTRAINT [PK_Recibos] PRIMARY KEY CLUSTERED ([Id] ASC),
    CONSTRAINT [FK_Recibos_CentrosCostos] FOREIGN KEY ([Id_CentroCosto]) REFERENCES [dbo].[CentrosCostos] ([Id]),
    CONSTRAINT [FK_Recibos_Sucursales] FOREIGN KEY ([Id_Sucursal]) REFERENCES [dbo].[Sucursales] ([Id]),
    CONSTRAINT [FK_Recibos_TalonariosComprobantes] FOREIGN KEY ([Id_TalonariosComprobantes]) REFERENCES [dbo].[TalonariosComprobantes] ([Id])
);

